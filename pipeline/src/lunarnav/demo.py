"""`lunarnav demo`: find the most dramatic real slip for the pitch (`docs/demo.md`).

Searches every curated site and baseline landing day, slipping 1..30 days later, for
(1) rank flips: site A beats site B at the baseline date but B beats A after the slip,
and (2) the largest single-site loss. Scores are "both" (Sun and Earth link) % of a
14-day mission at the app defaults (SPEC-app.md -> Controls), so the deployed app
reproduces them. The search walks hourly samples; the reported numbers for the winners
are recomputed with the 1-minute reference walk from `golden.py`.
"""

import re
from dataclasses import dataclass
from datetime import UTC, datetime, timedelta
from itertools import combinations
from typing import Any

import numpy as np
from numpy.typing import NDArray

from lunarnav import golden, io

MISSION_DAYS = 14
MAX_SLIP_DAYS = 30
FIRST_LANDING = datetime(2027, 1, 1, tzinfo=UTC)  # earlier dates are already past
MIN_WINNER_PCT = 20.0  # a flip between two near-dead sites is not a story
TOP_N = 3
START = "<!-- demo:scenarios:start (generated by `lunarnav demo`; do not edit) -->"
END = "<!-- demo:scenarios:end -->"

Scores = dict[str, NDArray[np.float64]]  # site id -> % per baseline landing day


@dataclass(frozen=True)
class SiteLoss:
    site_id: str
    base_day: int
    slip_days: int
    base_pct: float
    slip_pct: float
    drop_pct: float


@dataclass(frozen=True)
class RankFlip:
    winner_id: str  # ahead at the baseline date
    loser_id: str  # ahead after the slip
    base_day: int
    slip_days: int
    base_gap_pct: float  # winner - loser at baseline (> 0)
    slip_gap_pct: float  # winner - loser after the slip (< 0)
    swing_pct: float


def window_pcts(
    on: NDArray[np.bool_], samples_per_day: int, window_samples: int, n_days: int
) -> NDArray[np.float64]:
    """% of each window that is on, for windows starting at day 0..n_days-1."""
    starts = np.arange(n_days) * samples_per_day
    if starts.size and starts[-1] + window_samples > on.size:
        raise ValueError("a window runs past the end of the data")
    csum = np.concatenate(([0], np.cumsum(on, dtype=np.int64)))
    return 100.0 * (csum[starts + window_samples] - csum[starts]) / window_samples


def site_losses(
    both: Scores, max_slip_days: int, first_day: int, last_base_day: int
) -> list[SiteLoss]:
    """Each site's worst baseline->slip drop, sorted largest first."""
    out: list[SiteLoss] = []
    for site_id, pct in both.items():
        best: SiteLoss | None = None
        for slip in range(1, max_slip_days + 1):
            last = min(last_base_day, pct.size - 1 - slip)
            if last < first_day:
                continue
            base = pct[first_day : last + 1]
            drop = base - pct[first_day + slip : last + 1 + slip]
            i = int(np.argmax(drop))
            if best is None or drop[i] > best.drop_pct:
                best = SiteLoss(
                    site_id, first_day + i, slip, float(base[i]),
                    float(base[i] - drop[i]), float(drop[i]),
                )  # fmt: skip
        if best is not None:
            out.append(best)
    return sorted(out, key=lambda r: (-r.drop_pct, r.site_id))


def rank_flips(
    both: Scores,
    max_slip_days: int,
    first_day: int,
    last_base_day: int,
    min_winner_pct: float = 0.0,
) -> list[RankFlip]:
    """Best flip per site pair (largest swing in the score gap), largest first."""
    out: list[RankFlip] = []
    for a, b in combinations(sorted(both), 2):
        gap = both[a] - both[b]  # a - b
        best: RankFlip | None = None
        for slip in range(1, max_slip_days + 1):
            last = min(last_base_day, gap.size - 1 - slip)
            if last < first_day:
                continue
            g0 = gap[first_day : last + 1]
            g1 = gap[first_day + slip : last + 1 + slip]
            swing = np.where(g0 * g1 < 0, np.abs(g0 - g1), 0.0)
            # The baseline winner must itself score at least min_winner_pct.
            win_pct = np.where(
                g0 > 0,
                both[a][first_day : last + 1],
                both[b][first_day : last + 1],
            )
            swing = np.where(win_pct >= min_winner_pct, swing, 0.0)
            i = int(np.argmax(swing))
            if swing[i] > 0 and (best is None or swing[i] > best.swing_pct):
                sign = 1.0 if g0[i] > 0 else -1.0
                winner, loser = (a, b) if sign > 0 else (b, a)
                best = RankFlip(
                    winner, loser, first_day + i, slip,
                    float(sign * g0[i]), float(sign * g1[i]), float(swing[i]),
                )  # fmt: skip
        if best is not None:
            out.append(best)
    return sorted(out, key=lambda r: (-r.swing_pct, r.winner_id, r.loser_id))


def replace_section(doc: str, body: str) -> str:
    """Swap the generated block, leaving the rest of the doc untouched."""
    block = f"{START}\n{body}\n{END}"
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.DOTALL)
    if pattern.search(doc):
        return pattern.sub(lambda _: block, doc)
    return doc.rstrip("\n") + "\n\n" + block + "\n"


# --- search over the shipped data -------------------------------------------------


def _states(inputs: golden.Inputs, site: dict[str, Any]) -> dict[str, NDArray[Any]]:
    """Hourly Sun / Earth / both on-states over the whole ephemeris coverage."""
    eph = inputs.ephemeris
    t = eph.start_ms + np.arange(eph.count, dtype=np.float64) * eph.step_ms
    walk = golden._site_state(inputs, site, golden.OPTS["observerHeightM"], t)
    thr, hys = golden.OPTS["sunThreshold"], golden.OPTS["hysteresis"]
    sun = golden.hysteresis_states(
        walk["sunFraction"], min(1.0, thr + hys), max(0.0, thr - hys)
    )
    clearance = walk["earthElevDeg"] - walk["earthHorizonDeg"]
    clearance -= golden.OPTS["earthMarginDeg"]
    eh = golden.OPTS["earthHysteresisDeg"]
    earth = golden.hysteresis_states(clearance, eh, -eh)
    return {"sun": sun, "earth": earth, "both": sun & earth}


def _day_iso(inputs: golden.Inputs, day: int) -> str:
    start = datetime.fromtimestamp(inputs.ephemeris.start_ms / 1000, tz=UTC)
    return (start + timedelta(days=day)).strftime("%Y-%m-%dT%H:%M:%SZ")


def _refined(inputs: golden.Inputs, site_id: str, day: int) -> dict[str, Any]:
    """1-minute reference metrics for a 14-day mission landing at 00:00Z on `day`."""
    iso = _day_iso(inputs, day)
    t = golden._scenario(inputs, f"demo-{site_id}", site_id, iso)["totals"]
    return {
        "landing": iso,
        "sunlitPct": t["sunlitPct"],
        "earthPct": t["earthPct"],
        "bothPct": t["bothPct"],
        "firstSunsetH": t["firstSunsetH"],
        "longestSunGapH": t["longestSunGapH"],
    }


def _fmt(x: float | None, unit: str = "") -> str:
    return "never" if x is None else f"{x:.1f}{unit}"


def _row(
    inputs: golden.Inputs, names: dict[str, str], site_id: str, day: int, label: str
) -> str:
    m = _refined(inputs, site_id, day)
    return (
        f"| {label} | {names[site_id]} (`{site_id}`) | {str(m['landing'])[:10]} "
        f"| {_fmt(m['sunlitPct'], '%')} | {_fmt(m['earthPct'], '%')} "
        f"| **{_fmt(m['bothPct'], '%')}** | {_fmt(m['firstSunsetH'], ' h')} |"
    )


HEADER = (
    "| | Site | Landing (UTC 00:00) | Sunlit | Earth link | Both | First sunset |\n"
    "|---|---|---|---|---|---|---|"
)


def render_section(
    inputs: golden.Inputs, flips: list[RankFlip], losses: list[SiteLoss]
) -> str:
    names = {s["id"]: s["name"] for s in inputs.sites["sites"]}
    opts = golden.OPTS
    lines = [
        "## Demo scenarios (generated)",
        "",
        (
            f"Search: every curated site, baseline landings daily from "
            f"{FIRST_LANDING:%Y-%m-%d} to the end of the ephemeris, slips of 1-"
            f"{MAX_SLIP_DAYS} days later. Mission {MISSION_DAYS} days, observer "
            f"{opts['observerHeightM']} m, Sun threshold {opts['sunThreshold']}, Earth "
            f"margin {opts['earthMarginDeg']}° (app defaults). Ranking score is "
            f"**Both** (Sun and Earth link). The search uses hourly samples; the numbers "
            f"below are the 1-minute reference (`golden.py`) and match the app's engine "
            f"within its 10-minute tolerance."
        ),
        "",
        "### Rank flips: the best site changes after a slip",
        "",
    ]
    for n, f in enumerate(flips, 1):
        slipped = f.base_day + f.slip_days
        lines += [
            (
                f"**{n}. {names[f.winner_id]} vs {names[f.loser_id]}**: "
                f"slip {f.slip_days} days, landing {_day_iso(inputs, f.base_day)[:10]} "
                f"→ {_day_iso(inputs, slipped)[:10]}. Gap in Both %: "
                f"{f.base_gap_pct:+.1f} → {f.slip_gap_pct:+.1f} "
                f"(swing {f.swing_pct:.1f} points)."
            ),
            "",
            HEADER,
            _row(inputs, names, f.winner_id, f.base_day, "baseline"),
            _row(inputs, names, f.loser_id, f.base_day, "baseline"),
            _row(inputs, names, f.winner_id, slipped, f"slip +{f.slip_days} d"),
            _row(inputs, names, f.loser_id, slipped, f"slip +{f.slip_days} d"),
            "",
            (
                f"Reproduce: sites `{f.winner_id}` + `{f.loser_id}`, duration "
                f"{MISSION_DAYS} d, landing {_day_iso(inputs, f.base_day)}, slip "
                f"slider +{f.slip_days} d."
            ),
            "",
        ]
    lines += ["### Largest single-site losses", ""]
    for n, r in enumerate(losses, 1):
        slipped = r.base_day + r.slip_days
        lines += [
            (
                f"**{n}. {names[r.site_id]}**: slip {r.slip_days} days from "
                f"{_day_iso(inputs, r.base_day)[:10]}, Both {r.base_pct:.1f}% → "
                f"{r.slip_pct:.1f}% (−{r.drop_pct:.1f} points)."
            ),
            "",
            HEADER,
            _row(inputs, names, r.site_id, r.base_day, "baseline"),
            _row(inputs, names, r.site_id, slipped, f"slip +{r.slip_days} d"),
            "",
        ]
    return "\n".join(lines).rstrip("\n")


def find_scenarios(
    inputs: golden.Inputs,
) -> tuple[list[RankFlip], list[SiteLoss]]:
    eph = inputs.ephemeris
    if eph.step_ms != golden.H_MS:
        raise ValueError("demo search assumes an hourly ephemeris")
    window = MISSION_DAYS * 24
    n_days = (eph.count - window) // 24 + 1
    both: Scores = {}
    for site in inputs.sites["sites"]:
        on = _states(inputs, site)["both"]
        both[site["id"]] = window_pcts(on, 24, window, n_days)
    first = (FIRST_LANDING - datetime.fromtimestamp(eph.start_ms / 1000, tz=UTC)).days
    last = n_days - 1 - MAX_SLIP_DAYS
    flips = rank_flips(both, MAX_SLIP_DAYS, first, last, MIN_WINNER_PCT)
    losses = site_losses(both, MAX_SLIP_DAYS, first, last)
    return flips[:TOP_N], losses[:TOP_N]


def main() -> None:
    inputs = golden.load_inputs()
    flips, losses = find_scenarios(inputs)
    if not flips and not losses:
        raise SystemExit("no scenarios found; check the ephemeris and sites data")
    path = io.REPO_ROOT / "docs" / "demo.md"
    doc = path.read_text(encoding="utf-8") if path.exists() else "# Demo\n"
    path.write_text(
        replace_section(doc, render_section(inputs, flips, losses)), encoding="utf-8"
    )
    print(f"wrote {path} ({len(flips)} flips, {len(losses)} losses)")
